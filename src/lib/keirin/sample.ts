function marksOf(code: string): Race["sites"] {
  const sites = emptySites();
  const re = /([BYN])(\*)?/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(code))) {
    sites[m[1] as SiteKey] = { bet: true, hit: m[2] === "*" };
  }
  return sites;
}

export function makeSample(): Race[] {
  const chrono = RAW.map((row, i) => {
    const [order, payout2, payout3, racers, battle, winLine, tech, marks] = row;
    const [tech1, tech2 = ""] = tech.split("-");
    const n = i + 1;
    return {
      id: `sample-${String(n).padStart(2, "0")}`,
      raceNo: n,
      order,
      payout2,
      payout3,
      racers,
      battle,
      winLine,
      tech1,
      tech2,
      sites: marksOf(marks),
    } satisfies Race;
  });
  return chrono.reverse();
}
